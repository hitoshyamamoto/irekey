package model_test

import (
	"errors"
	"flag"
	"os"
	"regexp"
	"strings"
	"testing"
)

// The canonical vocabulary lives in the specification's glossary appendix.
// docs/glossary.md is generated from it, so the two never drift apart.
var update = flag.Bool("update", false, "rewrite docs/glossary.md from the specification")

const (
	specPath      = "../../docs/spec/masterprompt.md"
	glossaryPath  = "../../docs/glossary.md"
	appendixTitle = "## Appendix A — Glossary"
)

var entryLine = regexp.MustCompile(`^- \*\*([^*]+)\*\* — (.+)$`)

// specLabel matches the specification's internal identifiers (invariant,
// goal, gate, scenario, question, assumption, milestone and requirement
// IDs, and numbered section references). They must not reach the public glossary.
var specLabel = regexp.MustCompile(`\b(I[1-9][0-9]?|G[1-8]|V[1-6]|S[0-9]{2}|Q[0-9]{1,2}|A[1-5]|M[0-8]|N?FR-[0-9]{2})\b|\bSection [0-9]`)

type glossaryEntry struct {
	term string
	text string
}

// glossaryEntries returns the entries of the glossary appendix of spec, in
// order. An entry is a "- **term** — text" line; an indented line that
// follows it continues the entry.
func glossaryEntries(spec string) ([]glossaryEntry, error) {
	start := strings.Index(spec, appendixTitle+"\n")
	if start < 0 {
		return nil, errors.New("the specification has no glossary appendix")
	}
	body := spec[start+len(appendixTitle)+1:]
	if end := strings.Index(body, "\n## "); end >= 0 {
		body = body[:end]
	}
	var out []glossaryEntry
	for _, line := range strings.Split(body, "\n") {
		switch {
		case strings.HasPrefix(line, "- "):
			m := entryLine.FindStringSubmatch(line)
			if m == nil {
				return nil, errors.New("malformed glossary entry: " + line)
			}
			out = append(out, glossaryEntry{term: m[1], text: m[2]})
		case strings.HasPrefix(line, "  ") && len(out) > 0:
			out[len(out)-1].text += " " + strings.TrimSpace(line)
		}
	}
	if len(out) == 0 {
		return nil, errors.New("the glossary appendix has no entries")
	}
	return out, nil
}

// renderGlossary returns the content of docs/glossary.md.
func renderGlossary(entries []glossaryEntry) string {
	var b strings.Builder
	b.WriteString("# Glossary\n\n")
	b.WriteString("<!--\nGenerated from the glossary appendix of docs/spec/masterprompt.md by\n")
	b.WriteString("go test ./internal/model -run TestGlossaryIsInSync -update\n")
	b.WriteString("Do not edit this file by hand; change the specification instead.\n-->\n\n")
	b.WriteString("The canonical vocabulary of irekey. Every term is used exactly as\n")
	b.WriteString("defined here, in code, documentation, command output and logs.\n")
	b.WriteString("\"Not:\" lists confusions to avoid.\n\n")
	for _, e := range entries {
		b.WriteString("- **" + e.term + "** — " + e.text + "\n")
	}
	return b.String()
}

func readSpecGlossary(t *testing.T) []glossaryEntry {
	t.Helper()
	spec, err := os.ReadFile(specPath)
	if err != nil {
		t.Fatal(err)
	}
	entries, err := glossaryEntries(string(spec))
	if err != nil {
		t.Fatal(err)
	}
	return entries
}

func TestGlossaryIsInSync(t *testing.T) {
	want := renderGlossary(readSpecGlossary(t))
	if *update {
		if err := os.WriteFile(glossaryPath, []byte(want), 0o644); err != nil { //nolint:gosec // G306: a documentation file, readable by everyone
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(glossaryPath)
	if err != nil {
		t.Fatalf("%v (run go test ./internal/model -run TestGlossaryIsInSync -update)", err)
	}
	if string(got) != want {
		t.Errorf("docs/glossary.md differs from the specification's glossary (run go test ./internal/model -run TestGlossaryIsInSync -update)")
	}
}

func TestGlossaryIsSortedAndUnique(t *testing.T) {
	entries := readSpecGlossary(t)
	seen := make(map[string]bool)
	for i, e := range entries {
		key := strings.ToLower(e.term)
		if seen[key] {
			t.Errorf("term %q appears twice", e.term)
		}
		seen[key] = true
		if i > 0 && strings.ToLower(entries[i-1].term) > key {
			t.Errorf("term %q comes after %q; the glossary is alphabetical", e.term, entries[i-1].term)
		}
		if strings.TrimSpace(e.text) == "" {
			t.Errorf("term %q has no definition", e.term)
		}
	}
}

func TestGlossaryHasNoSpecificationLabels(t *testing.T) {
	for _, e := range readSpecGlossary(t) {
		if m := specLabel.FindString(e.term + " " + e.text); m != "" {
			t.Errorf("term %q contains the specification label %q; describe it in words", e.term, m)
		}
	}
}

func TestGlossaryEntries_Errors(t *testing.T) {
	tests := []struct {
		name string
		spec string
	}{
		{"no appendix", "# Spec\n\nnothing\n"},
		{"no entries", appendixTitle + "\n\nTerms are alphabetical.\n\n## Appendix B\n"},
		{"malformed entry", appendixTitle + "\n\n- term without bold\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if _, err := glossaryEntries(tt.spec); err == nil {
				t.Error("glossaryEntries succeeded; want an error")
			}
		})
	}
}

func TestGlossaryEntries_Continuation(t *testing.T) {
	spec := appendixTitle + "\n\n- **alpha** — first line\n  continued here.\n- **beta** — second.\n\n## Appendix B\n- **not** — a glossary entry.\n"
	entries, err := glossaryEntries(spec)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 2 || entries[0].text != "first line continued here." || entries[1].term != "beta" {
		t.Errorf("entries = %+v", entries)
	}
}

func TestSpecLabelPattern(t *testing.T) {
	tests := []struct {
		text  string
		label bool
	}{
		{"a verification step V1 to V6", true},
		{"see Section 10.6", true},
		{"the invariant I14", true},
		{"requirement FR-07", true},
		{"requirement NFR-01", true},
		{"scenario S05", true},
		{"question Q3", true},
		{"milestone M0", true},
		{"the IDs of the gates", false},
		{"SHA-256 and IPv4", false},
		{"a section of the file", false},
	}
	for _, tt := range tests {
		if got := specLabel.MatchString(tt.text); got != tt.label {
			t.Errorf("specLabel.MatchString(%q) = %v, want %v", tt.text, got, tt.label)
		}
	}
}
