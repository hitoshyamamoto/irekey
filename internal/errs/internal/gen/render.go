// notDefined stands for an empty signal or handling in the documentation.
const notDefined = "not defined yet"

// RenderGo returns the Go file of package errs that declares one constant
// per code and the registry the package looks codes up in. The registry
// must be valid.
func RenderGo(r *Registry) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// SPDX-License-Identifier: MIT\n\n")
	b.WriteString("// Code generated by errsgen from codes.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package errs\n\n")
	b.WriteString("// The registered error codes. Each constant is named after its code\n")
	b.WriteString("// without the dash; docs/errors.md describes every code.\n")
	b.WriteString("const (\n")
	for i, c := range r.Codes {
		if i == 0 || c.Category != r.Codes[i-1].Category {
			if i > 0 {
				b.WriteString("\n")
			}
			fmt.Fprintf(&b, "\t// %s\n\n", categoryHeading(r, c.Category))
		}
		fmt.Fprintf(&b, "\t// %s is %s, %s (%s).\n", ConstName(c.Code), c.Code, c.Title, c.Status)
		fmt.Fprintf(&b, "\t%s Code = %s\n", ConstName(c.Code), strconv.Quote(c.Code))
	}
	b.WriteString(")\n\n")
	b.WriteString("// registry holds every registered code, by category and then by number.\n")
	b.WriteString("var registry = []Info{\n")
	for _, c := range r.Codes {
		b.WriteString("\t{\n")
		field := func(name, value string) {
			fmt.Fprintf(&b, "\t\t%s: %s,\n", name, value)
		}
		field("Code", ConstName(c.Code))
		field("Category", strconv.Quote(c.Category))
		field("Title", strconv.Quote(c.Title))
		field("Condition", strconv.Quote(c.Condition))
		field("Signal", strconv.Quote(c.Signal))
		field("Handling", strconv.Quote(c.Handling))
		field("Exit", strconv.Quote(c.Exit))
		field("State", strconv.Quote(c.DeviceState))
		field("Kind", strconv.Quote(c.Kind))
		field("Status", strconv.Quote(c.Status))
		field("Since", strconv.Quote(c.Since))
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}

// categoryHeading returns "USR: operator input" for a prefix.
func categoryHeading(r *Registry, prefix string) string {
	for _, c := range r.Categories {
		if c.Prefix == prefix {
			return c.Prefix + ": " + c.Title
		}
	}
	return prefix
}

// RenderMarkdown returns docs/errors.md. The registry must be valid.
func RenderMarkdown(r *Registry) []byte {
	var b strings.Builder
	p := func(lines ...string) {
		for _, l := range lines {
			b.WriteString(l)
			b.WriteByte('\n')
		}
	}
	active := 0
	for _, c := range r.Codes {
		if c.Status == Active {
			active++
		}
	}

	p("<!-- Generated by errsgen from internal/errs/codes.yaml. DO NOT EDIT. -->",
		"",
		"# Error codes",
		"",
		"This file is generated from",
		"[`internal/errs/codes.yaml`](../internal/errs/codes.yaml); do not edit",
		"it. To change it, edit the registry and run `go generate ./internal/errs`.",
		"",
		"By design, every error irekey reports carries a stable code of the form",
		"`<CATEGORY>-<NNN>`, and a released code never changes meaning. The",
		"command-line conventions require every failure message to state what",
		"failed, the error code, the state the device was left in, and the next",
		"command to run. [ADR 0019](adr/0019-stable-error-code-registry.md)",
		"explains the registry.",
		"")
	p(fmt.Sprintf("The registry holds %d codes: %d active and %d reserved. An active code",
		len(r.Codes), active, len(r.Codes)-active),
		"is produced by irekey. A reserved code is registered, with its condition,",
		"exit code and device state, but no code path produces it yet. Its signal",
		"and handling describe the design where the specification defines them,",
		"not behavior that exists yet, and read \""+notDefined+"\" otherwise.",
		"",
		"Diagnostic commands follow a convention: for each problem they find,",
		"they report the code that a real operation would raise for the same",
		"problem, and have no codes of their own.",
		"")

	p("## Exit codes",
		"",
		"The exit codes become a stable contract at 1.0.",
		"",
		"| Exit code | Meaning | Device state |",
		"|---|---|---|")
	for _, d := range Exits {
		p(fmt.Sprintf("| %d | %s | %s |", d.Code, cell(d.Meaning), cell(d.State)))
	}
	p("")

	p("## Device states",
		"",
		"Every code states the state an error with that code leaves the device in.",
		"",
		"| Device state | Meaning |",
		"|---|---|")
	for _, d := range DeviceStates {
		p(fmt.Sprintf("| `%s` | %s |", d.Name, cell(d.Meaning)))
	}
	p("",
		"The exit code and the device state of a code can also be one of these",
		"rules:",
		"",
		"| Value | Meaning |",
		"|---|---|")
	for _, d := range StateRules {
		p(fmt.Sprintf("| `%s` | %s |", d.Name, cell(d.Meaning)))
	}
	p("",
		"The terminal outcome of each device in an operation maps to a device",
		"state:",
		"",
		"| Outcome | Device state |",
		"|---|---|")
	for _, o := range Outcomes {
		p(fmt.Sprintf("| `%s` | `%s` |", o.Name, o.State))
	}
	p("")

	p("## Codes set by phase",
		"",
		"A code whose exit is `by-phase` can occur at any point of an operation.",
		"What is known about the device-side work of the operation, its phase,",
		"sets the exit code and device state of such a code:",
		"",
		"| Phase | Exit code | Device state |",
		"|---|---|---|")
	for _, d := range Phases {
		p(fmt.Sprintf("| %s | %d | `%s` |", cell(d.Meaning), d.Exit, d.State))
	}
	p("",
		"For every other code, the phase can only make the result more",
		"pessimistic, never more optimistic. From the most to the least",
		"favorable, the device states are:",
		"",
		codeList(Pessimism)+".",
		"",
		"After the switch with a successful rollback, a code whose state is",
		"`unchanged` gives exit 7 and `previous-release`. When device-side work",
		"started and its outcome is unknown, a code whose state is more favorable",
		"than `unknown` gives exit 12 and `unknown`. When the rollback failed,",
		"every code gives exit 8 and `needs-intervention`. A code whose state is",
		"at least as pessimistic as the phase keeps its own exit code. The one",
		"result that the phase makes more favorable is an interruption (exit",
		"130): it is registered as `unknown` and is `unchanged` only when the",
		"caller states that no device-side work was involved.",
		"",
		"The specification's design for an error that no code classifies is to",
		"fail safe: abort before the switch and roll back after it. Today the",
		"error package resolves such an error to `BUG-003` with nothing known",
		"about device-side work: exit 15, device state `unknown`. It resolves an",
		"interruption that carries no code to `USR-006`: exit 130, device state",
		"`unknown`. A code attached to an error takes precedence over an",
		"interruption that the error wraps. A device state of `unknown` holds",
		"until `irekey status <device>` reconciles it.",
		"")

	p("## Categories",
		"",
		"| Prefix | Category | Covers |",
		"|---|---|---|")
	for _, c := range r.Categories {
		p(fmt.Sprintf("| [%s](#%s) | %s | %s |", c.Prefix, anchor(c.Prefix+": "+c.Title), cell(c.Title), cell(c.Covers)))
	}
	for _, cat := range r.Categories {
		p("", "## "+cat.Prefix+": "+cat.Title, "", "Covers: "+cat.Covers+".")
		for _, c := range r.Codes {
			if c.Category == cat.Prefix {
				renderCode(p, c)
			}
		}
	}
	return []byte(b.String())
}

func renderCode(p func(...string), c Code) {
	status := c.Status
	if status == Reserved {
		status = "reserved: not produced by any code path yet"
	}
	p("",
		"### "+c.Code+": "+c.Title,
		"",
		"| Field | Value |",
		"|---|---|",
		"| Condition | "+cell(c.Condition)+" |",
		"| Signal | "+orNotDefined(c.Signal)+" |",
		"| Handling | "+orNotDefined(c.Handling)+" |",
		"| Exit code | "+value(c.Exit)+" |",
		"| Device state | `"+c.DeviceState+"` |",
		"| Kind | "+c.Kind+" |",
		"| Status | "+status+" |",
		"| Since | "+c.Since+" |")
}

// codeList renders values as code, separated by commas.
func codeList(values []string) string {
	out := make([]string, len(values))
	for i, v := range values {
		out[i] = "`" + v + "`"
	}
	return strings.Join(out, ", ")
}

// value renders an exit field: a number as is, a rule as code.
func value(exit string) string {
	if _, err := strconv.Atoi(exit); err == nil {
		return exit
	}
	return "`" + exit + "`"
}

func orNotDefined(s string) string {
	if s == "" {
		return notDefined
	}
	return cell(s)
}

// cell escapes the pipe characters of a table cell.
func cell(s string) string {
	return strings.ReplaceAll(s, "|", `\|`)
}

// anchor returns the fragment GitHub gives a heading: lower case, spaces as
// dashes, punctuation other than dashes and underscores removed. Headings
// are ASCII, so no other letters occur.
//
// Verify: the heading anchor rules of GitHub-rendered Markdown (GitHub Docs,
// "Basic writing and formatting syntax", section links).
func anchor(heading string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(heading) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '-', r == '_':
			b.WriteRune(r)
		case r == ' ':
			b.WriteByte('-')
		}
	}
	return b.String()
}
