var update = flag.Bool("update", false, "rewrite golden files")

// golden compares got with testdata/<name>.golden, or rewrites the file
// with -update.
func golden(t *testing.T, name string, got []byte) {
	t.Helper()
	path := filepath.Join("testdata", name+".golden")
	if *update {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run go test ./internal/errs/internal/gen -update)", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s differs from %s (run go test ./internal/errs/internal/gen -update and review the diff):\n%s", name, path, got)
	}
}

func TestRenderGo(t *testing.T) {
	src, err := RenderGo(parseFixture(t))
	if err != nil {
		t.Fatal(err)
	}
	golden(t, "fixture.go", src)

	lines := strings.SplitN(string(src), "\n", 4)
	if lines[0] != "// SPDX-License-Identifier: MIT" || lines[2] != "// Code generated by errsgen from codes.yaml. DO NOT EDIT." {
		t.Errorf("the file starts with %q", lines[:3])
	}
	f, err := parser.ParseFile(token.NewFileSet(), "zz_generated_codes.go", src, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	if f.Name.Name != "errs" || f.Doc != nil {
		t.Errorf("package %s, doc comment %v: the generated file must not carry the package comment", f.Name.Name, f.Doc)
	}
}

func TestRenderGoFailsOnInvalidSource(t *testing.T) {
	r := parseFixture(t)
	// Not a valid registry, so not a valid identifier either.
	r.Codes[0].Code = "1SR-001"
	if _, err := RenderGo(r); err == nil {
		t.Error("RenderGo succeeded with an invalid constant name")
	}
}

func TestRenderMarkdown(t *testing.T) {
	md := RenderMarkdown(parseFixture(t))
	golden(t, "fixture.md", md)

	for _, want := range []string{
		"run `go generate ./internal/errs`",
		"The registry holds 7 codes: 1 active and 6 reserved.",
		"| 130 | interrupted by the operator; device-side work already started continues | unchanged or unknown |",
		"| [ENG](#eng-executor) | executor | lock held \\| journal damage |",
		"| Condition | truncated last journal line \\| recovered (warning) |",
		"| Signal | not defined yet |",
		"| Status | reserved: not produced by any code path yet |",
		"| Status | active |",
		"| Exit code | `by-phase` |",
		"| Device state | `per-device` |",
		"| Since | 0.2.0 |",
		"they report the code that a real operation would raise for the same\nproblem",
		"| nothing is known about device-side work | 15 | `unknown` |",
		"`unchanged`, `previous-release`, `unknown`, `needs-intervention`.",
	} {
		if !bytes.Contains(md, []byte(want)) {
			t.Errorf("docs/errors.md does not contain %q", want)
		}
	}
}

func TestAnchor(t *testing.T) {
	tests := map[string]string{
		"USR: operator input":                   "usr-operator-input",
		"ID: identity and authentication":       "id-identity-and-authentication",
		"BUG-003: unclassified error":           "bug-003-unclassified-error",
		"PLT-004: executor path mounted noexec": "plt-004-executor-path-mounted-noexec",
		"snake_case (kept)":                     "snake_case-kept",
	}
	for heading, want := range tests {
		if got := anchor(heading); got != want {
			t.Errorf("anchor(%q) = %q, want %q", heading, got, want)
		}
	}
}

