func TestSPDXFindings(t *testing.T) {
	tests := []struct {
		name    string
		path    string
		content string
		want    []int // lines with findings
	}{
		{"go with license", "a.go", goFile(""), nil},
		{"generated go", "gen.go", spdxGo + "\n\n// Code generated by stringer. DO NOT EDIT.\n\npackage p\n", nil},
		{"generated line first", "gen.go", "// Code generated by stringer. DO NOT EDIT.\n" + spdxGo + "\npackage p\n", []int{1}},
		{"go without license", "a.go", "package p\n", []int{1}},
		{"go license on line 2", "a.go", "\n" + spdxGo + "\n", []int{1}},
		{"go license with trailing text", "a.go", spdxGo + " OR Apache-2.0\n", []int{1}},
		{"go test file", "a_test.go", "package p\n", []int{1}},
		{"empty go file", "a.go", "", []int{1}},
		{"shell with license", "a.sh", "#!/bin/sh\n" + spdxShell + "\nset -eu\n", nil},
		{"bash shebang", "a.sh", "#!/usr/bin/env bash\n" + spdxShell + "\n", nil},
		{"shell without shebang", "a.sh", spdxShell + "\n", []int{1, 2}},
		{"shell without license", "a.sh", "#!/bin/sh\nset -eu\n", []int{2}},
		{"shell with license first", "a.sh", spdxShell + "\n#!/bin/sh\n", []int{1, 2}},
		{"empty shell file", "a.sh", "", []int{1, 2}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := spdxFindings(tt.path, []byte(tt.content))
			if len(got) != len(tt.want) {
				t.Fatalf("got %d findings %v, want lines %v", len(got), got, tt.want)
			}
			for i, f := range got {
				if f.line != tt.want[i] || f.path != tt.path {
					t.Errorf("finding %d = %v, want %s line %d", i, f, tt.path, tt.want[i])
				}
			}
		})
	}
}

func TestCheckSPDX_OnlyGoAndShellFiles(t *testing.T) {
	root := writeTree(t, map[string]string{
		"README.md":       "# Title\n",
		"config.yaml":     "a: b\n",
		"tool.py":         "print(1)\n",
		"cmd/x/main.go":   goFile("func main() {}"),
		"scripts/a.sh":    "#!/bin/sh\n" + spdxShell + "\n",
		"scripts/bad.sh":  "#!/bin/sh\n",
		"internal/bad.go": "package bad\n",
	})
	got, err := checkSPDX(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 2 || got[0].path != "internal/bad.go" || got[1].path != "scripts/bad.sh" {
		t.Errorf("findings = %v, want internal/bad.go and scripts/bad.sh", got)
	}
}
